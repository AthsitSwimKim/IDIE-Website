import { Fragment } from 'react'

/**
 * ศัพท์ไทยที่ห้ามถูกตัดขึ้นบรรทัดใหม่กลางวลี
 *
 * ทุกคำในรายการนี้เป็น**ศัพท์เฉพาะด้านความปลอดภัยหรือชื่อระบบ** ที่ถ้าครึ่งหนึ่ง
 * ไปอยู่คนละบรรทัด ผู้อ่านต้องปะติดปะต่อความหมายเอง เช่น "พื้นที่ | อันตราย"
 * ที่บรรทัดแรกจบด้วย "พื้นที่" เฉย ๆ ทำให้ตาอ่านผ่านไปโดยยังไม่รู้ว่าเป็นพื้นที่แบบใด
 *
 * **เกณฑ์การเพิ่มคำ** — ต้องเป็นวลีที่แยกแล้วเสียความหมาย ไม่ใช่แค่คำยาว
 * และต้องสั้นพอที่จะไม่กว้างเกินกล่องที่แคบที่สุดที่มันไปปรากฏ (นับที่จอ 320px)
 * เพราะ `whitespace-nowrap` ที่ยาวเกินกล่องจะ**ล้นออกนอกกรอบ**แทนที่จะตัด
 *
 * เรียงจากยาวไปสั้น เพื่อให้วลีที่ยาวกว่าถูกจับคู่ก่อนเสมอ —
 * "ชนิดกันระเบิด" ต้องชนะ "กันระเบิด" ไม่งั้นจะเหลือ "ชนิด" ค้างท้ายบรรทัดเหมือนเดิม
 */
const KEEP_TOGETHER = [
  'อุปกรณ์ส่งสัญญาณ',
  'สัญญาณเตือนภัย',
  'พื้นที่อันตราย',
  'ชนิดกันระเบิด',
  'กล้องวงจรปิด',
  'ระบบเครือข่าย',
].sort((a, b) => b.length - a.length)

const PATTERN = new RegExp(`(${KEEP_TOGETHER.join('|')})`, 'g')

export interface KeepPhrasesProps {
  /** ข้อความล้วน — ห้ามส่ง element เข้ามาเพราะต้องค้นหาวลีในสตริงจริง */
  children: string
}

/**
 * กันไม่ให้วลีศัพท์เฉพาะภาษาไทยถูกตัดคนละบรรทัด
 *
 * ต่างจาก `KeepWords` ที่กันการตัด**กลางคำเดียว** (ชื่อเฉพาะที่พจนานุกรมไม่รู้จัก
 * แล้วเบราว์เซอร์เดาตัดผิด เช่น "อินดัสเตรี | ยล") ตัวนี้กันการตัด**ระหว่างคำที่
 * ต้องอ่านด้วยกัน** ซึ่งเป็นจุดตัดที่ถูกต้องตามพจนานุกรมทุกประการ แต่อ่านแล้วสะดุด
 *
 * **ทำไมต้องเป็น span ไม่ใช่ CSS** — ทดสอบบนหน้าจริงแล้วทั้ง `word-break: keep-all`,
 * `word-break: break-word`, `line-break: strict` และค่า `normal` ให้ผลการตัดบรรทัด
 * **เหมือนกันทุกตัวอักษร** เบราว์เซอร์ตัดบรรทัดไทยด้วยพจนานุกรมในตัวซึ่ง CSS
 * ไม่มีคุณสมบัติไหนสั่งได้ ต้องบอกเป็นราย "ก้อน" ว่าห้ามตัดข้างในเท่านั้น
 *
 * ใช้กับข้อความที่เป็นสตริงเดียวเท่านั้น ไม่รองรับ element ซ้อน —
 * ถ้าวันหนึ่งต้องใส่ตัวหนาหรือลิงก์ในประโยคเดียวกัน ต้องแยกเป็นหลายชิ้นแล้วครอบทีละชิ้น
 */
export function KeepPhrases({ children }: KeepPhrasesProps) {
  const parts = children.split(PATTERN)

  return (
    <>
      {parts.map((part, index) =>
        // ชิ้นที่ index เป็นเลขคี่คือกลุ่มที่ถูกจับด้วยวงเล็บใน regex = วลีที่ต้องคุม
        index % 2 === 1 ? (
          <span key={`${index}-${part}`} className="whitespace-nowrap">
            {part}
          </span>
        ) : (
          <Fragment key={`${index}-${part}`}>{part}</Fragment>
        ),
      )}
    </>
  )
}
