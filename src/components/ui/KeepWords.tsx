import { Fragment } from 'react'

export interface KeepWordsProps {
  /** ข้อความล้วน — ห้ามส่ง element เข้ามาเพราะต้องแยกคำด้วยช่องว่างจริง */
  children: string
}

/**
 * กันไม่ให้บรรทัดถูกตัดกลางคำ — ใช้กับชื่อเฉพาะภาษาไทยที่อยู่ในหัวข้อ
 *
 * **ปัญหาที่แก้** — เบราว์เซอร์ตัดบรรทัดภาษาไทยด้วยพจนานุกรมในตัว ไม่ได้ตัดที่ช่องว่าง
 * อย่างเดียว พอเจอคำที่พจนานุกรมไม่รู้จัก (ชื่อบริษัท คำทับศัพท์) มันจะเดาแล้วตัดผิดที่
 * ของจริงที่เจอ: "บริษัท ไอดี อินดัสเตรี / ยล เอ็นจิเนียริ่ง จำกัด" — คำว่า
 * "อินดัสเตรียล" ถูกหั่นเป็น "อินดัสเตรี" กับ "ยล"
 *
 * **ทำไมต้องเป็น span ไม่ใช่ CSS** — ทดสอบแล้วทั้ง `word-break: keep-all`,
 * `line-break: strict`, `word-break: auto-phrase` และ `overflow-wrap` ทุกค่า
 * ไม่มีอันไหนหยุดการตัดตามพจนานุกรมได้เลย ต้องบอกเป็นราย "ก้อน" ว่าห้ามตัดข้างใน
 *
 * **ทำไมไม่ใช้ U+2060 WORD JOINER** — ได้ผลเหมือนกันแต่เป็นอักขระซ่อนที่ติดไปด้วย
 * เวลาผู้ใช้คัดลอกชื่อบริษัทไปวางในเอกสารอื่น วิธีนี้ข้อความที่คัดลอกได้เหมือนต้นฉบับเป๊ะ
 *
 * ใช้เท่าที่จำเป็น — ถ้าคำเดียวยาวเกินความกว้างกล่องจริง ๆ มันจะล้นแทนที่จะตัด
 * จึงเหมาะกับชื่อเฉพาะสั้น ๆ ไม่ใช่ย่อหน้าเนื้อความ
 */
export function KeepWords({ children }: KeepWordsProps) {
  const words = children.split(' ')

  return (
    <>
      {words.map((word, index) => (
        <Fragment key={`${index}-${word}`}>
          {index > 0 && ' '}
          <span className="whitespace-nowrap">{word}</span>
        </Fragment>
      ))}
    </>
  )
}
