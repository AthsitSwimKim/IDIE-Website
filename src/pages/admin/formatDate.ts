/**
 * แสดงวันที่ตามโซนเวลาของเครื่องผู้ใช้
 *
 * ค่าที่ API ส่งมาเป็น ISO ที่ลงท้ายด้วย Z (UTC) เสมอ — `toLocaleDateString`
 * จึงแปลงกลับเป็นเวลาไทยให้เองบนเครื่องของทีมงาน ไม่ต้องคำนวณ offset เอง
 *
 * แยกออกมาเป็นไฟล์กลางเพราะมีสองหน้าที่แสดงวันที่ (รายการข่าวกับแดชบอร์ด)
 * ถ้าต่างคนต่างเขียน วันเดียวกันจะแสดงคนละรูปแบบในหน้าที่อยู่ห่างกันแค่คลิกเดียว
 */
export function formatDate(iso: string) {
  return new Date(iso).toLocaleDateString('th-TH', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  })
}
